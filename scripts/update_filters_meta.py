#!/usr/bin/env python3
"""Generate filter name maps from the AdGuard registries.

The script writes two files:

- ``filters-meta.js`` for regular filters;
- ``dns-filters-meta.js`` for DNS filters.

The source files have a .js extension but contain JSON. The script uses only
the Python standard library.
"""

from __future__ import annotations

import json
import urllib.request
from pathlib import Path

SOURCES: list[tuple[str, str, str]] = [
    (
        "https://raw.githubusercontent.com/AdguardTeam/FiltersRegistry/"
        "refs/heads/master/platforms/android/filters.js",
        "filters-meta.js",
        "ADGUARD_FILTER_NAMES",
    ),
    (
        "https://raw.githubusercontent.com/AdguardTeam/HostlistsRegistry/"
        "refs/heads/main/assets/filters.json",
        "dns-filters-meta.js",
        "ADGUARD_DNS_FILTER_NAMES",
    ),
]
ROOT = Path(__file__).resolve().parents[1]
USER_AGENT = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
    "AppleWebKit/537.36 (KHTML, like Gecko) "
    "Chrome/155.0.8059.85 Safari/537.36"
)


def load_filters(url: str) -> list[dict[str, object]]:
    request = urllib.request.Request(
        url,
        headers={"User-Agent": USER_AGENT},
    )
    with urllib.request.urlopen(request, timeout=60) as response:
        data = json.load(response)
    filters = data.get("filters")
    if not isinstance(filters, list):
        raise ValueError(f"{url} does not contain a filters array")
    return filters


def build_names(filters: list[dict[str, object]]) -> dict[int, str]:
    names: dict[int, str] = {}
    for item in filters:
        filter_id = item.get("filterId")
        name = item.get("name")
        if filter_id is None or not name:
            continue
        names[int(filter_id)] = str(name)
    return names


def render(names: dict[int, str], global_name: str) -> str:
    lines = [
        "// Generated by scripts/update_filters_meta.py. Do not edit.",
        f"window.{global_name} = {{",
    ]
    for filter_id in sorted(names):
        name = json.dumps(names[filter_id], ensure_ascii=False)
        lines.append(f"  {filter_id}: {name},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def write_meta(url: str, output_name: str, global_name: str) -> None:
    names = build_names(load_filters(url))
    if not names:
        raise ValueError(f"no filters with a name were found in {url}")
    output_path = ROOT / output_name
    with output_path.open("w", encoding="utf-8", newline="\n") as output:
        output.write(render(names, global_name))
    print(f"Wrote {output_path} ({len(names)} filters)")


def main() -> int:
    for url, output_name, global_name in SOURCES:
        write_meta(url, output_name, global_name)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
